#!/usr/bin/env node
/**
 * Compile `scripts/anny/atlas-poses.json` into the module the app imports.
 *
 *   npm run gen:envelope-poses
 *
 * WHY GENERATED, AND NOT A TABLE SOMEONE MAINTAINS. Which pose an atlas needs is
 * a MEASUREMENT — `scripts/anny/measure_atlas_pose.mjs` derives it from each
 * atlas's own bone geometry — and D18 is unambiguous that a measured value must
 * never be typed into prose or code by hand. It has already cost this repository
 * once: hand-written structure ids in a generated document went stale silently
 * and would have masked the wrong anatomy. A hand-written pose assignment fails
 * the same way and is harder to see, because a body posed wrongly still looks
 * like a body.
 *
 * ⚠️ THE URLS ARE WRITTEN OUT AS LITERALS, and that is a BUILD REQUIREMENT
 * rather than a style choice. `pruneUnshippedModels` in `vite.config.ts` decides
 * which GLBs survive into `dist` by regex-scanning source for
 * `/models/<name>.glb`. A template literal is invisible to it — which is exactly
 * how the five body envelopes were silently pruned from a production build once
 * already, shipping the whole feature as "not installed" pills while the dev
 * server looked fine. This generator emits literals for that reason; do not
 * "simplify" them into interpolation.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = process.cwd()
const IN = join(ROOT, 'scripts/anny/atlas-poses.json')
const OUT = join(ROOT, 'src/scene/envelopePoses.ts')

if (!existsSync(IN)) {
  console.error(`✗ ${IN} is missing — run \`npm run measure:atlas-pose\` first`)
  process.exit(1)
}

const spec = JSON.parse(readFileSync(IN, 'utf8'))
const poseIds = Object.keys(spec.poses).sort()
// An empty `poses` is reachable — the measurement emits it when no atlas yields
// a complete limb on both sides, which a partial asset set can produce — and
// rendering it would write `export type EnvelopePoseId = ` with no right-hand
// side, a syntax error that surfaces two commands later in `tsc` rather than
// here. Refuse before writing, as the missing-input branch above does.
if (poseIds.length === 0) {
  console.error(
    `✗ ${IN} defines no poses — nothing to generate. Re-run \`npm run measure:atlas-pose\` ` +
      'with the atlas assets present.',
  )
  process.exit(1)
}
const modes = Object.entries(spec.atlases)
  .map(([id, a]) => [id, a.poseId ?? null])
  .sort(([a], [b]) => a.localeCompare(b))

/** Only the two adult presets are posed — see the note in the emitted file. */
const PRESETS = ['anny-adult-f', 'anny-adult-m']

const urlRows = poseIds
  .map((pose) => {
    const inner = PRESETS.map(
      (p) => `    '${p}': '/models/${p}.pose-${pose}.glb',`,
    ).join('\n')
    return `  '${pose}': {\n${inner}\n  },`
  })
  .join('\n')

const modeRows = modes
  .map(([mode, pose]) => {
    const entry = spec.atlases[mode]
    const why = pose
      ? entry.inheritsFrom
        ? `inherits ${entry.inheritsFrom}`
        : `measured from ${entry.measuredFrom}`
      : 'nothing measurable — rest pose'
    return `  '${mode}': ${pose ? `'${pose}'` : 'null'}, // ${why}`
  })
  .join('\n')

const summary = poseIds
  .map((p) => {
    const entry = spec.poses[p]
    // The total comes from the spec, not from a literal: a segment added to the
    // measurement's table must not leave this generated line claiming "/8".
    const all = Object.values(entry.segments)
    const driven = all.filter((s) => s.source === 'measured').length
    return (
      ` *   ${p.padEnd(20)} ${driven}/${all.length} segments measured — ` +
      `covers ${entry.members.join(', ')}`
    )
  })
  .join('\n')

const out = `/**
 * Which posed envelope each anatomy mode wants.
 *
 * ⚠️ GENERATED by \`scripts/gen-envelope-poses.mjs\` from
 * \`scripts/anny/atlas-poses.json\`. Do not hand-edit: every value here is a
 * measurement of an atlas's own bone geometry, and D18 forbids typing one of
 * those by hand. Regenerate with \`npm run gen:envelope-poses\`.
 *
 * WHAT THIS IS FOR. D16 measured that the envelope encloses the torso and not
 * the limbs, because ANNY rests in a wide A-pose while most atlases here stand
 * with their arms down — an ANGULAR difference no uniform scale can close. It
 * recorded the fix as "rigging the envelope and posing it per atlas, which is
 * real work and is not done here". This is the result of that work: one bake per
 * distinct atlas pose, chosen at runtime by the mode on screen.
 *
 * The poses, as measured:
 *
${summary}
 *
 * ⚠️ ONLY THE TWO ADULT PRESETS ARE POSED. \`child\`, \`elder\` and \`pregnant\` are
 * shape studies against adult anatomy — D16a refuses that pairing as a DEFAULT
 * while allowing it as a deliberate choice — so posing them would spend assets
 * making an incoherent pairing look more convincing. They keep the rest pose.
 */

import type { BodyEnvelopeId } from './bodyEnvelopes'

/** A pose id, as measured. \`null\` means the envelope stays in ANNY's rest pose. */
export type EnvelopePoseId = ${poseIds.map((p) => `'${p}'`).join(' | ')}

/** The posed asset for a (pose, preset) pair. */
export const POSED_ENVELOPE_URLS: Record<
  EnvelopePoseId,
  Partial<Record<BodyEnvelopeId, string>>
> = {
${urlRows}
}

/**
 * The pose each anatomy mode resolves to.
 *
 * Keyed by \`AnatomyMode\` — including the composed modes, which take the pose of
 * whichever atlas supplies their musculoskeletal system, since that is the
 * geometry that determines where the limbs are.
 */
export const MODE_POSE: Record<string, EnvelopePoseId | null> = {
${modeRows}
}

/** Every posed url, for the availability probe. */
export const POSED_ENVELOPE_URL_LIST: readonly string[] = Object.values(POSED_ENVELOPE_URLS)
  .flatMap((byPreset) => Object.values(byPreset))
  .filter((u): u is string => typeof u === 'string')

/**
 * The url to load for a mode and preset, or \`null\` to use the rest-pose asset.
 *
 * Returns null for any preset with no posed bake, so the caller falls back to
 * the unposed envelope rather than requesting a file that was never made.
 */
export function posedEnvelopeUrl(
  mode: string | null | undefined,
  envelope: BodyEnvelopeId,
): string | null {
  const pose = mode ? MODE_POSE[mode] : null
  if (!pose) return null
  return POSED_ENVELOPE_URLS[pose]?.[envelope] ?? null
}
`

writeFileSync(OUT, out)
console.log(`wrote ${OUT}`)
console.log(`  ${poseIds.length} poses, ${modes.length} modes, ${poseIds.length * PRESETS.length} urls`)
for (const [mode, pose] of modes) console.log(`    ${mode.padEnd(20)} ${pose ?? 'rest'}`)
