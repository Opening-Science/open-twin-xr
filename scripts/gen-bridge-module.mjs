#!/usr/bin/env node
/**
 * Compile `docs/fma-uberon-bridge.tsv` into a TypeScript module the app bundles.
 *
 *   npm run gen:bridge-module
 *
 * WHY A MODULE AND NOT A FETCHED ASSET. The bridge is 143 rows — a few kB — and
 * it is the one piece of the ontology work that is COMMITTED, unlike every GLB.
 * Shipping it as a fetchable file in `public/` would give it the same "might not
 * be installed" failure mode as an atlas, for data that is always present in the
 * repository. Bundling removes a network round trip and a whole class of missing
 * asset handling from the search path.
 *
 * ⚠️ GENERATED. Do not hand-edit `src/scene/bridgeData.ts`. The TSV is generated
 * in turn by `npm run build:bridge` from UBERON's own published cross-references,
 * so a hand edit here would be inventing an equivalence twice removed from its
 * source. If a mapping is wrong, fix it upstream and regenerate both.
 *
 * ⚠️ `ambiguous` ROWS ARE CARRIED THROUGH, NOT RESOLVED. UBERON sometimes lists
 * several FMA terms for one concept, which is a one-to-many correspondence rather
 * than an identity. Collapsing them here would manufacture a precision the source
 * does not have; the search surfaces them as several candidates instead.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = process.cwd()
const IN = join(ROOT, 'docs/fma-uberon-bridge.tsv')
const OUT = join(ROOT, 'src/scene/bridgeData.ts')

if (!existsSync(IN)) {
  console.error(`✗ ${IN} is missing — run \`npm run build:bridge\` first`)
  process.exit(1)
}

const rows = readFileSync(IN, 'utf8')
  .split('\n')
  .filter((l) => l.trim() && !l.startsWith('#'))
  .map((l) => l.split('\t'))
  .filter((c) => c.length >= 5)

const header = rows.shift()
if (header[0] !== 'uberon') {
  console.error(`✗ unexpected header: ${header.join(', ')}`)
  process.exit(1)
}

/** uberon -> {label, fma[], ambiguous} */
const entries = []
for (const [uberon, label, fma, confidence] of rows) {
  const ids = fma.split('|').filter(Boolean)
  if (!ids.length) continue
  entries.push({ uberon, label, fma: ids, ambiguous: confidence === 'ambiguous' })
}

const lines = []
lines.push('// GENERATED by scripts/gen-bridge-module.mjs — do not edit by hand.')
lines.push('// Source: docs/fma-uberon-bridge.tsv, itself generated by `npm run build:bridge`')
lines.push('// from UBERON\'s own published cross-references via the EBI OLS4 API.')
lines.push('')
lines.push('export interface BridgeEntry {')
lines.push('  uberon: string')
lines.push('  label: string')
lines.push('  /** One or more FMA terms UBERON cross-references for this concept. */')
lines.push('  fma: string[]')
lines.push('  /**')
lines.push('   * UBERON lists MORE THAN ONE FMA term here, so this is a one-to-many')
lines.push('   * correspondence rather than an identity. Show every candidate; never')
lines.push('   * silently pick the first.')
lines.push('   */')
lines.push('  ambiguous: boolean')
lines.push('}')
lines.push('')
lines.push(`/** ${entries.length} UBERON concepts with an FMA cross-reference. */`)
lines.push('export const FMA_UBERON_BRIDGE: readonly BridgeEntry[] = [')
for (const e of entries) {
  lines.push(
    `  { uberon: '${e.uberon}', label: ${JSON.stringify(e.label)}, ` +
      `fma: [${e.fma.map((f) => `'${f}'`).join(', ')}], ambiguous: ${e.ambiguous} },`,
  )
}
lines.push(']')
lines.push('')

writeFileSync(OUT, lines.join('\n'))
console.log(`wrote ${OUT} — ${entries.length} bridged concepts`)
